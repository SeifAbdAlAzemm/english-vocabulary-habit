import "server-only";
import { createServerClient } from "@supabase/ssr";
import { cookies } from "next/headers";
import { redirect } from "next/navigation";
import { connection } from "next/server";
import { supabaseConfig } from "./config";

export async function createClient() {
  // Auth reads Date.now() internally to check token expiry. Cookies alone can
  // also be available during a partial prerender/prefetch; wait for the actual
  // request before constructing or invoking Auth. loading.tsx supplies the
  // Suspense fallback for initial rendering and client navigations.
  await connection();
  const store = await cookies();
  const { url, key } = supabaseConfig();
  return createServerClient(url, key, {
    cookies: {
      getAll: () => store.getAll(),
      setAll: (values) => {
        try { values.forEach(({ name, value, options }) => store.set(name, value, options)); }
        catch { /* Server Components cannot write cookies; proxy refreshes them. */ }
      },
    },
  });
}

export async function requireLearner() {
  const supabase = await createClient();
  const { data, error } = await supabase.auth.getUser();
  if (error || !data.user) redirect("/login");
  return { supabase, user: data.user };
}
